import type { ChatRun, ServerMessage } from "./chat-types";
import { formatDateTime, formatDuration } from "./utils";

export interface ExportPayload {
  agent: string;
  exportedAt: number;
  runs: readonly ChatRun[];
  serverMessages?: readonly ServerMessage[];
}

export function buildMarkdownExport({ agent, exportedAt, runs, serverMessages }: ExportPayload): string {
  const lines: string[] = [
    `# Fleet transcript — ${agent}`,
    "",
    `Exported: ${new Date(exportedAt).toISOString()}`,
    `Runs: ${runs.length}`,
    "",
  ];

  if (runs.length === 0) {
    lines.push("_No browser-recorded runs yet._", "");
  }

  runs.forEach((run, index) => {
    lines.push(
      "---",
      "",
      `## ${index + 1}. ${run.status === "done" ? "Done" : run.status === "error" ? "Error" : "Unanswered"} · ${formatDateTime(run.createdAt)}`,
      "",
      `- requestId: \`${run.requestId}\``,
      `- operationId: \`${run.operationId ?? "—"}\``,
      `- model: \`${run.model ?? "fleet default"}\``,
      `- latency: ${formatDuration(run.latencyMs)}`,
    );
    if (run.reason) lines.push(`- reason: \`${run.reason}\``);
    if (run.error) lines.push(`- error: ${run.error}`);
    lines.push("", "### Prompt", "", run.prompt, "", "### Response", "", run.text || "_No text returned._", "");
  });

  if (serverMessages && serverMessages.length > 0) {
    lines.push("---", "", "## Durable transcript (server preview)", "");
    for (const message of serverMessages) {
      lines.push(
        `### ${message.kind ?? "message"} · ${String(message.id ?? "?")}`,
        "",
        message.preview,
        "",
      );
    }
  }

  lines.push("---", "", "Generated by Fleet UI.", "");
  return lines.join("\n");
}

export function buildJsonExport(payload: ExportPayload): string {
  return JSON.stringify(
    {
      format: "fleet-ui/transcript@1",
      agent: payload.agent,
      exportedAt: new Date(payload.exportedAt).toISOString(),
      runs: payload.runs,
      serverMessages: payload.serverMessages ?? [],
    },
    null,
    2,
  );
}

export function buildPlainTranscript(runs: readonly ChatRun[]): string {
  const chunks: string[] = [];
  for (const run of runs) {
    chunks.push(`You:\n${run.prompt}`, `Fleet:\n${run.text || (run.error ?? "—")}`);
  }
  return chunks.join("\n\n");
}
